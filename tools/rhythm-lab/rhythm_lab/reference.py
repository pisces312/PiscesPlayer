"""Cached Beat This! reference beats for the baseline song.

The reference is model output, not ground-truth annotation, so it is regenerated by
`compute_reference.py` and committed as a small text fixture. It is only meaningful for
the song in `baseline.json`; every consumer must treat it as optional.
"""

from pathlib import Path

import numpy as np

from .config import LAB_DIR

REFERENCE_DIR = LAB_DIR / "reference"
DEFAULT_BEATS_FILE = REFERENCE_DIR / "beat_this_final0_fine.txt"
DEFAULT_DOWNBEATS_FILE = REFERENCE_DIR / "beat_this_final0_fine_down.txt"


def load_beats(path: Path = DEFAULT_BEATS_FILE) -> np.ndarray:
    if not path.is_file():
        raise SystemExit(
            f"missing reference beats {path}; run `run_lab.py reference` "
            "(needs tools/rhythm-lab/.venv with beat-this)"
        )
    beats = np.loadtxt(path)
    if beats.ndim == 0:
        beats = beats.reshape(1)
    if beats.size < 2:
        raise SystemExit(f"reference file {path} has fewer than two beats")
    return np.asarray(beats, dtype=np.float64)


def load_downbeats(path: Path = DEFAULT_DOWNBEATS_FILE) -> np.ndarray:
    if not path.is_file():
        return np.zeros(0)
    values = np.loadtxt(path)
    return np.atleast_1d(values).astype(np.float64)
