        .map { MusicQuizText.normalizeTitle(it) }
        .filter { it.isNotEmpty() }
        .toSet()

    /** Tier A hit: the normalized title contains one of the catalog names (aliases included). */
    fun matches(title: String): Boolean {
        val key = MusicQuizText.normalizeTitle(title)
        if (key.isEmpty()) return false
        return keys.any { MusicQuizText.containsPhrase(key, it) }
    }
